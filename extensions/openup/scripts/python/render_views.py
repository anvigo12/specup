@view(".specify/wbs/wbs.md")
def _wbs(graph, config) -> str:
    if not graph.wbs:
        return _page("Work Breakdown Structure", ".specify/wbs/wbs.yaml", "_No WBS nodes._")

    # A nested list, not an indented table: the WBS is a tree, and a list renders as one both
    # in Markdown and in the raw file. Table cells padded with &nbsp; do neither.
    rows = []
    for node_id in sorted(graph.wbs, key=lambda n: [int(s) for s in n[len("WBS-"):].split(".")]):
        node = graph.wbs[node_id]
        level = wbs_level(node_id)
        facts = [f"*L{level} {validate_wbs.LEVEL_NAMES.get(level, '?')}*"]
        facts += [str(node[key]) for key in ("kind", "owner", "iteration", "status") if node.get(key)]
        line = f"{'  ' * (level - 1)}- **`{node_id}`** {node.get('name', '')} — {' · '.join(facts)}"
        links = [f"{label} {_cell(node.get(key))}"
                 for key, label in (("requirements", "implements"), ("risks", "mitigates"),
                                    ("acceptance", "covers"), ("evidence", "evidenced by"))
                 if node.get(key)]
        if links:
            line += f"<br>\n{'  ' * (level - 1)}  {'; '.join(links)}"
        rows.append(line)

    # Early termination is a deliberate, declared exception to the seven-level model. It has
    # to be visible in the view, or the reason for the exception lives only in the YAML.
    terminal = [f"- `{nid}` — {node['terminal_reason']}"
                for nid, node in sorted(graph.wbs.items()) if node.get("terminal_reason")]
    blocks = ["\n".join(rows), ""]
    if terminal:
        blocks += [f"## Declared early termination ({config['wbs'].get('depth_policy', 'semantic')} policy)",
                   "", "\n".join(terminal), ""]

    program = graph.wbs_doc.get("program")
    return _page(f"Work Breakdown Structure — {program}" if program else "Work Breakdown Structure",
                 ".specify/wbs/wbs.yaml", *blocks)


