@view(".specify/traceability/traceability.md")
def _traceability(graph, config) -> str:
    if not graph.edges:
        return _page("Traceability Graph", "the configured traceability stores", "_No edges._")

    blocks: list[str] = []
    by_relation: dict[str, list] = {}
    for edge in graph.edges:
        by_relation.setdefault(edge.relation, []).append(edge)

    for relation in sorted(by_relation):
        rows = ["| From | To | Provenance | Status | Declared in |", "|---|---|---|---|---|"]
        for edge in sorted(by_relation[relation], key=lambda e: (e.from_id, e.to_id)):
            if edge.provenance == "derived":
                mark = f"derived (`{edge.derived_by}`)"
            elif edge.provenance == "approved":
                mark = f"approved ({_cell((edge.approval or {}).get('by'))})"
            else:
                mark = "asserted"
            rows.append(
                f"| `{edge.from_id}` | `{edge.to_id}` | {mark} "
                f"| {_cell(edge.status)} | `{_cell(edge.source_file)}` |"
            )
        blocks += [f"## {relation} ({len(by_relation[relation])})", "", "\n".join(rows), ""]

    return _page("Traceability Graph", "the configured traceability stores",
                 f"Inverses are derived at load time and never stored, so each edge appears "
                 f"once, in active voice. {len(graph.edges)} edge(s) across "
                 f"{len(graph.raw_stores)} store(s).", "", *blocks)


@view(".specify/traceability/coverage.md")
def _coverage(graph, config) -> str:
    class _Args:
        root = str(graph.root)
        json = False

    metrics = validate_trace.validate(_Args()).metrics
    thresholds = config["traceability"]["coverage_thresholds"]
    edges = metrics.get("edges", 0) or 1

    def pct(key: str) -> str:
        return f"{metrics.get(key, 0):.0%}"

    coverage = [
        "| Metric | Value | Threshold |", "|---|---|---|",
        f"| Requirement → implementation | {pct('forward_coverage')} | {thresholds.get('forward', 1.0):.0%} |",
        f"| Requirement → verification | {pct('verification_coverage')} | {thresholds.get('forward', 1.0):.0%} |",
        f"| Source → requirement (backward) | {pct('backward_coverage')} | {thresholds.get('backward', 0.95):.0%} |",
        f"| Acceptance criterion → scenario | {pct('scenario_coverage')} | 100% |",
        f"| Source → test | {pct('code_test_coverage')} | reported, not gated |",
    ]

    class _RiskArgs:
        root = str(graph.root)
        json = False

    risk_metrics = validate_risk.validate(_RiskArgs()).metrics
    coverage += [
        f"| Open risk → mitigation | {risk_metrics.get('mitigation_coverage', 0):.0%} | 100% for high exposure |",
        f"| Open risk → evidence | {risk_metrics.get('evidence_coverage', 0):.0%} | reported, not gated |",
    ]

    # The provenance mix belongs here and not only in the audit: a coverage figure built from
    # unverifiable claims is not coverage, and speckit.openup.trace.md promises the mix on
    # this page. Both signed labels are split into what survives a re-check and what does not.
    reproduced = metrics.get("derived_verified", 0)
    unreproduced = metrics.get("derived_unverified", 0)
    approved = metrics.get("approved_verified", 0)
    stale = metrics.get("approved_stale", 0)
    asserted = metrics.get("provenance_mix", {}).get("asserted", 0)
    verifiable = (reproduced + approved) / edges

    mix = [
        "| Provenance | Edges | Share | What it is worth |", "|---|---|---|---|",
        f"| derived, reproduced | {reproduced} | {reproduced / edges:.0%} | A rule re-ran and produced it (TRC-010) |",
        f"| derived, unreproduced | {unreproduced} | {unreproduced / edges:.0%} | Names a rule that is not implemented — **not evidence** |",
        f"| approved, current | {approved} | {approved / edges:.0%} | Signed off, and still matching what was signed (TRC-013) |",
        f"| approved, stale | {stale} | {stale / edges:.0%} | Approved for content that has since changed — **not evidence** |",
        f"| asserted | {asserted} | {asserted / edges:.0%} | An agent or author claim only |",
    ]

    return _page("Traceability Coverage", "validate_trace.py",
                 "## Coverage", "", "\n".join(coverage), "",
                 "## Evidence quality", "", "\n".join(mix), "",
                 f"**{verifiable:.0%} of edges are independently verifiable.** That is the "
                 f"figure `traceability_final` scores at the release gate, and it counts only "
                 f"the two rows a third party could check without taking anyone's word for it. "
                 f"A graph can be 100% covered and still prove very little.")


