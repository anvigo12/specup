@view(".specify/risks/risk-register.md")
def _risks(graph, config) -> str:
    if not graph.risks:
        return _page("Risk Register", ".specify/risks/risk-register.yaml", "_No risks registered._")

    high = config["risk"].get("high_exposure_threshold", 0.40)
    critical = config["risk"].get("critical_exposure_threshold", 0.65)

    def exposure(risk: dict) -> float:
        return risk.get("probability", 0) * risk.get("impact", 0)

    rows = ["| Risk | Exposure | P × I | Status | Owner | Mitigation | Verification | Residual |",
            "|---|---|---|---|---|---|---|---|"]
    for risk_id, risk in sorted(graph.risks.items(), key=lambda kv: -exposure(kv[1])):
        value = exposure(risk)
        band = "🔴 critical" if value >= critical else "🟠 high" if value >= high else "🟡 moderate"
        rows.append(
            f"| `{risk_id}` {_cell(risk.get('title'))} | {value:.2f} {band} "
            f"| {risk.get('probability', 0)} × {risk.get('impact', 0)} "
            f"| {_cell(risk.get('status'))} | {_cell(risk.get('owner'))} "
            f"| {_cell(risk.get('mitigation'))} | {_cell(risk.get('verification'))} "
            f"| {risk.get('residual_exposure', '—')} |"
        )

    return _page("Risk Register", ".specify/risks/risk-register.yaml",
                 "\n".join(rows), "",
                 f"Thresholds: high ≥ {high:.2f}, critical ≥ {critical:.2f} "
                 f"(`openup-config.yml`, `risk.*_exposure_threshold`). Exposure is "
                 f"probability × impact and is recomputed by `validate_risk.py`; a hand-edited "
                 f"`exposure:` field fails `RISK-001`.")


