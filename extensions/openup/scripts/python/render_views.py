@view(".specify/governance/quality-gates.md")
def _quality_gates(graph, config) -> str:
    gates = config.get("gates", {})
    if not gates:
        return _page("Quality Gates", "openup-config.yml", "_No gates configured._")

    blocks: list[str] = []
    for name, spec in gates.items():
        rows = ["| Condition | What it checks |", "|---|---|"]
        for condition_name in spec.get("conditions", []):
            description = evaluate_gate.DESCRIPTIONS.get(
                condition_name,
                "**Not implemented.** A condition named here but absent from evaluate_gate.py "
                "fails the gate closed.",
            )
            rows.append(f"| `{condition_name}` | {description} |")
        blocks += [f"## {name}", "", f"Phase: **{spec.get('phase', '—')}**", "",
                   "\n".join(rows), ""]

    return _page("Quality Gates", "openup-config.yml",
                 "Every condition below is a named predicate implemented in "
                 "`evaluate_gate.py`, from which these descriptions are taken. A gate "
                 "passes only if all of its conditions pass; absence of evidence fails a "
                 "condition rather than skipping it.", "", "```bash",
                 "python3 .specify/extensions/openup/scripts/python/evaluate_gate.py "
                 "--gate GATE-LIFECYCLE_ARCHITECTURE --json", "```", "", *blocks)


