#!/usr/bin/env python3
"""Generate the Markdown views from the canonical YAML.

specup.md s47 exists to stop humans maintaining duplicated artifacts, and s65 says plainly:
"Do not manually maintain traceability documents. Generate traceability views from structured
relationships." Until this script, three commands asked *the agent* to regenerate wbs.md,
risk-register.md, traceability.md and coverage.md by hand — manual maintenance with an extra
failure mode, since an LLM transcribing YAML into Markdown is non-deterministic, unreviewable
(every regeneration is a fresh diff) and free to disagree with the canonical data.

Two of the governance documents are generated here for the same reason: a Definition of Ready
that disagrees with select_work.py, or a gate description that overstates what evaluate_gate.py
checks, is worse than no document at all — people read the document while the machine applies
the code.

    render_views.py            report which views are missing or stale (exit 1 if any are)
    render_views.py --write    regenerate them all

No view carries a timestamp. A generated_at line would make every file differ from the one on
disk on every run, which would turn the staleness check into noise and train people to ignore it.
"""

from __future__ import annotations

import sys
from typing import Any, Callable

import evaluate_gate
import select_work
import validate_done
import validate_risk
import validate_trace
import validate_wbs
from openup_model import GraphError, Verdict, base_parser, load_graph, run, wbs_level

BANNER = "<!-- GENERATED by render_views.py — do not edit. Regenerate with: render_views.py --write -->"

RENDERERS: dict[str, Callable[[Any, dict], str]] = {}


def view(path: str):
    def register(fn):
        RENDERERS[path] = fn
        return fn
    return register


def _page(title: str, source: str, *blocks: str) -> str:
    """Every view opens the same way: what it is, and what it was generated from."""
    head = [BANNER, "", f"# {title}", "", f"*Generated from `{source}`. Edit the source, not this file.*", ""]
    return "\n".join(head + list(blocks)).rstrip() + "\n"


def _cell(value: Any) -> str:
    """Render a value for a Markdown table cell, keeping a pipe from breaking the row."""
    if value is None or value == [] or value == {}:
        return "—"
    if isinstance(value, list):
        return ", ".join(f"`{item}`" for item in value)
    return str(value).replace("|", "\\|")


