# CLI
# --------------------------------------------------------------------------


def render_all(graph, config) -> dict[str, str]:
    return {path: renderer(graph, config) for path, renderer in sorted(RENDERERS.items())}


def write_views(args) -> int:
    graph, config = load_graph(args.root)
    written, unchanged = [], []
    for relative, content in render_all(graph, config).items():
        target = graph.root / relative
        if target.is_file() and target.read_text() == content:
            unchanged.append(relative)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        written.append(relative)

    for relative in written:
        print(f"  wrote      {relative}")
    for relative in unchanged:
        print(f"  unchanged  {relative}")
    print(f"\n{len(written)} view(s) regenerated, {len(unchanged)} already current")
    return 0


def validate(args) -> Verdict:
    graph, config = load_graph(args.root)
    verdict = Verdict("render-views")

    problems: list[str] = []
    for relative, content in render_all(graph, config).items():
        target = graph.root / relative
        if not target.is_file():
            problems.append(f"{relative}: missing — run render_views.py --write")
        elif target.read_text() != content:
            problems.append(f"{relative}: stale — the canonical source has moved on, or the "
                            f"file was hand-edited")
    if problems:
        verdict.fail("VIEW-001", f"{len(problems)} view(s) missing or stale", problems)
    else:
        verdict.ok("VIEW-001", f"all {len(RENDERERS)} generated view(s) match their sources")

    # A .md sitting beside a canonical store that no renderer owns is either a stale view from
    # an earlier layout or a hand-written document in a generated place. WARN: it may be
    # deliberate, and deleting someone's document is not this script's call.
    owned = set(RENDERERS)
    strays = [
        f"{rel}: carries the generated banner but no renderer owns it"
        for rel in sorted(
            str(p.relative_to(graph.root))
            for directory in (".specify/wbs", ".specify/risks", ".specify/traceability",
                              ".specify/governance")
            for p in (graph.root / directory).glob("*.md") if p.is_file()
        )
        if rel not in owned and BANNER.split(" — ")[0] in (graph.root / rel).read_text()
    ]
    if strays:
        verdict.warn("VIEW-002", f"{len(strays)} generated file(s) with no source", strays)
    else:
        verdict.ok("VIEW-002", "no generated view is left without a source")

    verdict.metrics = {"views": len(RENDERERS), "stale_or_missing": len(problems),
                       "orphaned": len(strays)}
    return verdict


def main() -> int:
    parser = base_parser(__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true",
                        help="regenerate every view instead of reporting on it")
    if "--write" in sys.argv[1:]:
        args = parser.parse_args()
        try:
            return write_views(args)
        except GraphError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2
    return run(validate, parser)


if __name__ == "__main__":
    sys.exit(main())
